// TestGeneratedCodeInsertCollisionRegression forces the generated-code path to
// hit a real MySQL duplicate during INSERT. It covers both the generic master
// create handler and the specialized employee transaction.
func TestGeneratedCodeInsertCollisionRegression(t *testing.T) {
	dsn := os.Getenv("TEST_DATABASE_DSN")
	if dsn == "" {
		t.Skip("TEST_DATABASE_DSN is not set; skipping MySQL generated-code integration test")
	}
	db, err := gorm.Open(gormmysql.Open(dsn), &gorm.Config{})
	if err != nil {
		t.Fatal(err)
	}

	n := time.Now().UnixNano() % 1_000_000
	clientCollision := fmt.Sprintf("CLI-%06d", n)
	clientRetry := fmt.Sprintf("CLI-%06d", (n+1)%1_000_000)
	employeeCollision := fmt.Sprintf("EMP-%06d", (n+2)%1_000_000)
	employeeRetry := fmt.Sprintf("EMP-%06d", (n+3)%1_000_000)
	if clientRetry == clientCollision || employeeRetry == employeeCollision {
		t.Fatal("test code allocation unexpectedly collided")
	}
	if err := db.Table("clients").Create(map[string]any{"client_code": clientCollision, "name": "コード衝突既存得意先"}).Error; err != nil {
		t.Fatalf("create collision client: %v", err)
	}
	var clientCollisionID uint64
	if err := db.Table("clients").Select("id").Where("client_code = ?", clientCollision).Take(&clientCollisionID).Error; err != nil {
		t.Fatalf("load collision client: %v", err)
	}
	if err := db.Table("employees").Create(map[string]any{"employee_code": employeeCollision, "status": "active", "full_name": "コード衝突既存従業員"}).Error; err != nil {
		t.Fatalf("create collision employee: %v", err)
	}
	var employeeCollisionID uint64
	if err := db.Table("employees").Select("id").Where("employee_code = ?", employeeCollision).Take(&employeeCollisionID).Error; err != nil {
		t.Fatalf("load collision employee: %v", err)
	}
	t.Cleanup(func() {
		for _, row := range []struct {
			table string
			code  string
			key   string
		}{
			{"clients", clientCollision, "client_code"},
			{"clients", clientRetry, "client_code"},
			{"employees", employeeCollision, "employee_code"},
			{"employees", employeeRetry, "employee_code"},
		} {
			if err := db.Table(row.table).Where(row.key+" = ?", row.code).Delete(map[string]any{}).Error; err != nil {
				t.Errorf("cleanup %s %s: %v", row.table, row.code, err)
			}
			var remaining int64
			if err := db.Table(row.table).Where(row.key+" = ?", row.code).Count(&remaining).Error; err != nil {
				t.Errorf("verify cleanup %s %s: %v", row.table, row.code, err)
			} else if remaining != 0 {
				t.Errorf("cleanup left %d %s rows for %s", remaining, row.table, row.code)
			}
		}
	})

	originalGenerator := businessCodeGenerator
	t.Cleanup(func() { businessCodeGenerator = originalGenerator })
	generated := map[string][]string{
		"CLI": {clientCollision, clientRetry},
		"EMP": {employeeCollision, employeeRetry},
	}
	calls := map[string]int{}
	businessCodeGenerator = func(prefix string) (string, error) {
		values := generated[prefix]
		index := calls[prefix]
		calls[prefix]++
		if index >= len(values) {
			return "", fmt.Errorf("unexpected generated-code request for %s", prefix)
		}
		return values[index], nil
	}

	gin.SetMode(gin.TestMode)
	router := gin.New()
	handler := NewMasterHandler(db)
	router.POST("/clients", handler.create("clients", clientColumns))
	router.POST("/employees", handler.createEmployee)
	request := func(path string, payload map[string]any) *httptest.ResponseRecorder {
		t.Helper()
		body, marshalErr := json.Marshal(payload)
		if marshalErr != nil {
			t.Fatal(marshalErr)
		}
		response := httptest.NewRecorder()
		router.ServeHTTP(response, httptest.NewRequest(http.MethodPost, path, bytes.NewReader(body)))
		return response
	}
	if response := request("/clients", map[string]any{"name": "コード再試行得意先"}); response.Code != http.StatusCreated {
		t.Fatalf("generic create collision retry = %d %s", response.Code, response.Body.String())
	}
	if response := request("/employees", map[string]any{"full_name": "コード再試行従業員", "status": "active"}); response.Code != http.StatusOK {
		t.Fatalf("specialized create collision retry = %d %s", response.Code, response.Body.String())
	}
	if calls["CLI"] != 2 || calls["EMP"] != 2 {
		t.Fatalf("generated-code calls = CLI:%d EMP:%d, want two each", calls["CLI"], calls["EMP"])
	}
	for _, row := range []struct {
		table string
		key   string
		code  string
	}{
		{"clients", "client_code", clientRetry},
		{"employees", "employee_code", employeeRetry},
	} {
		var count int64
		if err := db.Table(row.table).Where(row.key+" = ?", row.code).Count(&count).Error; err != nil || count != 1 {
			t.Fatalf("retry did not insert %s %s: count=%d err=%v", row.table, row.code, count, err)
		}
	}

	// A collision on the unrelated internal-id unique key must be returned, not
	// treated as a generated-code collision and retried.
	generated["EMP"] = []string{fmt.Sprintf("EMP-%06d", (n+4)%1_000_000)}
	calls["EMP"] = 0
	err = insertWithGeneratedCode(db, "employees", "employee_code", "EMP", map[string]any{
		"id":            employeeCollisionID,
		"status":        "active",
		"full_name":     "不正な内部ID重複",
		"employee_code": "ignored",
	})
	if err == nil {
		t.Fatal("unrelated internal-id unique violation unexpectedly succeeded")
	}
	if calls["EMP"] != 1 {
		t.Fatalf("unrelated unique violation retried %d times", calls["EMP"])
	}
}

